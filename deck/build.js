const F = { head: "Cambria", body: "Calibri" };
const M = 0.7;
const W = 13.33 - M * 2;

const pres = new pptxgen();
pres.layout = "LAYOUT_WIDE";
pres.author = "Управление e-commerce, ЗАО ПАТИО";
pres.title = "Тендерный калькулятор";

let n = 0;
function slide(title) {
  const s = pres.addSlide();
  s.background = { color: C.white };
  n += 1;
  if (title) {
    s.addText(title, {
      isTextBox: true, x: M, y: 0.45, w: W, h: 0.55,
      fontFace: F.head, fontSize: 28, bold: true, color: C.ink, margin: 0,
    });
  }
  s.addText(String(n), {
    isTextBox: true, x: 12.1, y: 6.95, w: 0.53, h: 0.3, align: "right",
    fontFace: F.body, fontSize: 10, color: C.line, margin: 0,
  });
  return s;
}
function txt(s, t, o) {
  s.addText(t, Object.assign({
    isTextBox: true, fontFace: F.body, fontSize: 14, color: C.ink,
    lineSpacing: 21, margin: 0, valign: "top",
  }, o));
}
function tbl(s, rows, o) {
  s.addTable(rows, Object.assign({
    x: M, w: W, fontFace: F.body, fontSize: 12.5, color: C.ink,
    border: { type: "solid", pt: 0.75, color: C.line },
    fill: { color: C.white }, valign: "middle", margin: [5, 8, 5, 8],
  }, o));
}

